"""Writes the probe's programs: each GLSL program in a folder of recorded ones (Dusklight's
platforms/xenon/shaders), with the length and hash of the SPIR-V the PC's glslang made for it, which a shader pack
built from that folder holds (Dusklight's platforms/xenon/glsl_pack.c, from Aurora's tools/build_glsl_pack.py).

    gen_programs.py <shader folder> <pack .c> <programs.h>

The hash is FNV-1a over each SPIR-V word's bytes, low byte first, as vulkan4xenon hashes SPIR-V.
"""

import re
import sys
from pathlib import Path

FNV_OFFSET_BASIS = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
STAGES = {"vert": "EShLangVertex", "frag": "EShLangFragment"}


def fnv1a_64(words):
    value = FNV_OFFSET_BASIS
    for word in words:
        for shift in (0, 8, 16, 24):
            value = ((value ^ ((word >> shift) & 0xFF)) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def pack_spirv(pack):
    """Each program's SPIR-V words in the pack, by its file name."""
    found = {}
    for name, stage, body in re.findall(r"glsl_([0-9a-f]{16})_(vert|frag)_spirv\[\] = \{([^}]*)\}", pack):
        found[f"{name}.{stage}"] = [int(word, 16) for word in re.findall(r"0x[0-9A-Fa-f]+", body)]
    return found


def c_string(text):
    out = []
    for line in text.splitlines(keepends=True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
        out.append(f'\t\t"{escaped}"')
    return "\n".join(out) if out else '\t\t""'


def main():
    folder, pack = Path(sys.argv[1]), Path(sys.argv[2]).read_text(encoding="utf-8")
    spirv = pack_spirv(pack)
    programs = sorted(p for p in folder.iterdir() if p.suffix[1:] in STAGES)
    missing = [p.name for p in programs if p.name not in spirv]
    if missing:
        sys.exit(f"gen_programs.py: not in the pack: {', '.join(missing)}")
    lines = ["// Generated by xsdk/gen_programs.py; don't edit.",
             "struct Program {\n\tconst char* name;\n\tEShLanguage stage;\n\tconst char* source;"
             "\n\tunsigned pcWords;\n\tunsigned long long pcHash;\n};\n",
             "static const Program programs[] = {"]
    for path in programs:
        words = spirv[path.name]
        lines.append(f'\t{{ "{path.name}", {STAGES[path.suffix[1:]]},')
        lines.append(c_string(path.read_text(encoding="utf-8")) + ",")
        lines.append(f"\t\t{len(words)}, 0x{fnv1a_64(words):016X}ull }},")
    lines.append("};")
    Path(sys.argv[3]).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
